#!/usr/bin/env node
// scripts/build-geoid-grid.mjs — regenerates src/data/egm96Grid.generated.js.
//
// The app used to ship `egm96-universal` itself: its 15' EGM96 grid is a
// 2.77 MB base64 chunk (1.87 MB gzipped) that the HUD's ALT readout fetches
// on every default load, because the intro fly-to ends 600 m over Austin
// where N ≈ -27 m is 4% of the reading. Resampling that grid at 0.5° and
// interpolating bilinearly stays within 1.1 m of it everywhere (200 000
// random points: p50 0.03 m, p99 0.49 m) at a fifth of the size, so the
// package is now a devDependency used only here and in the regeneration test.
//
// Layout: 361 rows (lat 90 → -90) × 721 columns (lon -180 → 180, both ends
// kept so interpolation never wraps), N in whole decimetres as little-endian
// int16, base64-encoded. EGM96 is NGA public-domain data; egm96-universal is
// MIT.
//
// Usage: node scripts/build-geoid-grid.mjs            (writes the module)
//        node scripts/build-geoid-grid.mjs --check    (exit 1 if stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { meanSeaLevel } from 'egm96-universal';

export const GRID_STEP_DEG = 0.5;
export const GRID_ROWS = 361;
export const GRID_COLS = 721;
export const OUTPUT = fileURLToPath(new URL('../src/data/egm96Grid.generated.js', import.meta.url));

/** @returns {string} the full source text of the generated module */
export function renderGridModule() {
  const bytes = Buffer.alloc(GRID_ROWS * GRID_COLS * 2);
  for (let row = 0; row < GRID_ROWS; row += 1) {
    const lat = 90 - row * GRID_STEP_DEG;
    for (let col = 0; col < GRID_COLS; col += 1) {
      const lon = -180 + col * GRID_STEP_DEG;
      bytes.writeInt16LE(Math.round(meanSeaLevel(lat, lon) * 10), (row * GRID_COLS + col) * 2);
    }
  }
  return [
    '// GENERATED by scripts/build-geoid-grid.mjs from egm96-universal — do not edit.',
    `// EGM96 geoid undulation N, ${GRID_STEP_DEG}° grid, ${GRID_ROWS} rows (lat 90 → -90) × ${GRID_COLS} cols`,
    '// (lon -180 → 180), whole decimetres, little-endian int16, base64.',
    `export const GRID_STEP_DEG = ${GRID_STEP_DEG};`,
    `export const GRID_ROWS = ${GRID_ROWS};`,
    `export const GRID_COLS = ${GRID_COLS};`,
    `export const GRID_DM_INT16LE_BASE64 = '${bytes.toString('base64')}';`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = renderGridModule();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== text) {
      console.error(`${OUTPUT} is stale: run node scripts/build-geoid-grid.mjs`);
      process.exit(1);
    }
    console.log('geoid grid module is current');
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`wrote ${OUTPUT} (${text.length} bytes)`);
  }
}
